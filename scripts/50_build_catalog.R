# Build the NYC data catalog ----
#
# Merges the two profile indexes (profiles/index.csv for the raw and derived sources,
# streets/profiles/index.csv for the street network history in derived/streets) into one catalog
# that lists every dataset in nyc_transport_data with the exact call to read it. Writes
# nyc_data_catalog.csv (machine-readable) and nyc_data_catalog.md (the signpost every README and
# CLAUDE.md points to). File paths are relative to the store root.
#
# Run from the repo root:  Rscript scripts/50_build_catalog.R
# Re-run after rebuilding either set of profiles so the catalog follows the data.

library(data.table)

# Read the two indexes ----
main_index    <- "profiles/index.csv"
streets_index <- "streets/profiles/index.csv"
if (!file.exists(main_index) || !file.exists(streets_index))
  stop("run from the nyc_transport repo root: ", normalizePath("."))

read_index <- function(path, section) {
  dt <- fread(path)
  dt[, section := section]
  dt[]
}

cat_dt <- rbindlist(list(
  read_index(main_index,    "raw and derived"),
  read_index(streets_index, "street network history (derived/streets)")
), use.names = TRUE, fill = TRUE)

keep <- c("section", "source", "reader", "files", "rows_total", "geometry", "crs", "notes")
cat_dt <- cat_dt[, ..keep]
setorder(cat_dt, section, source)

# Machine-readable catalog ----
fwrite(cat_dt, "nyc_data_catalog.csv")

# Markdown catalog ----
md_escape <- function(x) gsub("|", "\\|", as.character(x), fixed = TRUE)
fmt_rows  <- function(x) ifelse(is.na(x) | x == "", "", format(as.numeric(x), big.mark = ",", scientific = FALSE, trim = TRUE))

lines <- c(
  "# NYC data catalog",
  "",
  paste0("_Generated by `nyc_transport_repo/scripts/50_build_catalog.R` on ", Sys.Date(),
         ". Do not edit by hand; re-run after rebuilding the profiles._"),
  "",
  "Every dataset in `nyc_transport_data/` and the exact call to read it. Paths are relative to the",
  "store root. One source() loads every reader, including the street network history:",
  "",
  "```r",
  "source(Find(file.exists, c(\"../nyc_transport_repo/R/nyc_transport.R\", \"../nyc_transport/R/nyc_transport.R\")))",
  "```",
  ""
)

for (sec in unique(cat_dt[, section])) {
  d <- cat_dt[section == sec]
  lines <- c(lines,
    paste0("## ", sec, "  (", nrow(d), " datasets)"),
    "",
    "| source | read with | rows | geometry | notes |",
    "|---|---|---|---|---|")
  for (i in seq_len(nrow(d))) {
    lines <- c(lines, paste0(
      "| `", md_escape(d[i, source]), "` ",
      "| `", md_escape(d[i, reader]), "` ",
      "| ", fmt_rows(d[i, rows_total]), " ",
      "| ", md_escape(d[i, geometry]), " ",
      "| ", md_escape(d[i, notes]), " |"))
  }
  lines <- c(lines, "")
}

writeLines(lines, "nyc_data_catalog.md")

cat("wrote nyc_data_catalog.csv and nyc_data_catalog.md:",
    nrow(cat_dt), "datasets in", length(unique(cat_dt[, section])), "sections\n")
