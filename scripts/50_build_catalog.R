# Build the unified NYC data catalog ----
#
# Merges the per-store profile indexes (nyc_traffic_repo/profiles/index.csv and
# nyc_streets_repo/profiles/index.csv) into one catalog that lists every dataset across both
# stores with the exact call to read it. Writes nyc_data_catalog.csv (machine-readable) and
# nyc_data_catalog.md (the signpost every README and CLAUDE.md points to).
#
# Run from the nyc_traffic repo root:  Rscript scripts/50_build_catalog.R
# Re-run after rebuilding either store's profiles so the catalog follows the data.

library(data.table)

# Locate the two indexes ----
traffic_index <- "profiles/index.csv"
streets_index <- Find(file.exists, c(
  "../nyc_streets_repo/profiles/index.csv",
  "../nyc_streets/profiles/index.csv"
))
if (!file.exists(traffic_index)) stop("run from the nyc_traffic repo root: ", normalizePath("."))
if (is.null(streets_index)) stop("nyc_streets profiles/index.csv not found next to this repo")

# Read and stack ----
read_index <- function(path, store) {
  dt <- fread(path)
  dt[, store := store]
  dt[]
}

cat_dt <- rbindlist(list(
  read_index(traffic_index, "nyc_traffic_data"),
  read_index(streets_index, "nyc_streets_data")
), use.names = TRUE, fill = TRUE)

keep <- c("store", "source", "reader", "files", "rows_total", "geometry", "crs", "notes")
cat_dt <- cat_dt[, ..keep]
setorder(cat_dt, store, source)

# Machine-readable catalog ----
fwrite(cat_dt, "nyc_data_catalog.csv")

# Markdown catalog ----
md_escape <- function(x) gsub("|", "\\|", as.character(x), fixed = TRUE)
fmt_rows  <- function(x) ifelse(is.na(x) | x == "", "", format(as.numeric(x), big.mark = ",", scientific = FALSE, trim = TRUE))

lines <- c(
  "# NYC data catalog",
  "",
  paste0("_Generated by `nyc_traffic_repo/scripts/50_build_catalog.R` on ", Sys.Date(),
         ". Do not edit by hand; re-run after rebuilding either store's profiles._"),
  "",
  "Every dataset across both NYC data stores and the exact call to read it. Source the readers first:",
  "",
  "```r",
  "source(Find(file.exists, c(\"../nyc_traffic_repo/R/nyc_traffic.R\", \"../nyc_traffic/R/nyc_traffic.R\")))  # all readers below",
  "source(Find(file.exists, c(\"../nyc_streets_repo/R/streets.R\",     \"../nyc_streets/R/streets.R\")))      # street-history readers",
  "```",
  ""
)

for (st in unique(cat_dt[, store])) {
  d <- cat_dt[store == st]
  lines <- c(lines,
    paste0("## ", st, "  (", nrow(d), " datasets)"),
    "",
    "| source | read with | rows | geometry | notes |",
    "|---|---|---|---|---|")
  for (i in seq_len(nrow(d))) {
    lines <- c(lines, paste0(
      "| `", md_escape(d[i, source]), "` ",
      "| `", md_escape(d[i, reader]), "` ",
      "| ", fmt_rows(d[i, rows_total]), " ",
      "| ", md_escape(d[i, geometry]), " ",
      "| ", md_escape(d[i, notes]), " |"))
  }
  lines <- c(lines, "")
}

writeLines(lines, "nyc_data_catalog.md")

cat("wrote nyc_data_catalog.csv and nyc_data_catalog.md:",
    nrow(cat_dt), "datasets across", length(unique(cat_dt[, store])), "stores\n")
